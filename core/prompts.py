def build_revision_prompt(
    current_data: Dict[str, Any],
    revision_instruction: str,
    is_presentation: bool = False
) -> str:
    """Prompt to revise an existing document or presentation according to user instructions."""
    doc_type_str = "презентации" if is_presentation else "реферата/доклада"
    return f"""
Ты — академический редактор МГЭИ им. А.Д. Сахарова БГУ.
Тебе предоставлен текущий JSON с содержимым {doc_type_str}.

ТЕКУЩЕЕ СОДЕРЖИМОЕ:
{json.dumps(current_data, ensure_ascii=False, indent=2)}

ИНСТРУКЦИЯ ПОЛЬЗОВАТЕЛЯ ПО ПРАВКЕ:
«{revision_instruction}»

ЗАДАЧА:
Внеси точные, аккуратные изменения в структуру и текст согласно инструкции пользователя.
Сохраняй строгий академический стиль, стандарты оформления и формат JSON.
Не удаляй нетронутые разделы, а только улучшай/модифицируй то, о чем попросил пользователь.

Верни СТРОГО обновленный JSON с сохранением исходной структуры полей.
"""
